// Writes `out/_headers` (Cloudflare Pages) after `pnpm build:static`. A static export does not run `headers()` from
// next.config.ts, so the same headers are produced from the same function, `securityHeaders` in src/lib/csp.ts.
// Run with type stripping (`node --experimental-strip-types`), because csp.ts is TypeScript.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { securityHeaders } from '../src/lib/csp.ts';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'out');

/** The text of `_headers`: every path gets the security headers. */
export function headersFile(env = process.env) {
  const lines = securityHeaders(env).map(([name, value]) => `  ${name}: ${value}`);
  return [
    '# Generated by scripts/write-headers.mjs from src/lib/csp.ts. Do not edit.',
    '/*',
    ...lines,
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const target = join(OUT, '_headers');
  writeFileSync(target, headersFile());
  process.stdout.write(`Wrote ${target}\n`);
}
