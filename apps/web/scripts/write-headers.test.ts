import { describe, expect, it, vi } from 'vitest';
import config from '../next.config';
import { headersFile } from './write-headers.mjs';

const env = {
  NEXT_PUBLIC_API_URL: 'https://api.example.com',
  NEXT_PUBLIC_SANDBOX_ORIGIN: 'https://runner.example.net',
};

describe('_headers', () => {
  it('carries exactly the headers next.config sends, so dev and the static site agree', async () => {
    vi.stubEnv('NEXT_PUBLIC_API_URL', env.NEXT_PUBLIC_API_URL);
    vi.stubEnv('NEXT_PUBLIC_SANDBOX_ORIGIN', env.NEXT_PUBLIC_SANDBOX_ORIGIN);
    const fromConfig = (await config.headers?.())?.[0]?.headers ?? [];
    expect(fromConfig.length).toBeGreaterThan(0);
    const lines = fromConfig.map(({ key, value }) => `  ${key}: ${value}`);
    expect(headersFile(process.env)).toBe(
      [
        '# Generated by scripts/write-headers.mjs from src/lib/csp.ts. Do not edit.',
        '/*',
        ...lines,
        '',
      ].join('\n'),
    );
    vi.unstubAllEnvs();
  });

  it('has the frame-src of the sandbox runner, nosniff and a referrer policy, for every path', () => {
    const text = headersFile(env);
    expect(text).toContain('\n/*\n');
    expect(text).toContain(
      "Content-Security-Policy: frame-src https://runner.example.net; img-src 'self' data:",
    );
    expect(text).toContain('X-Content-Type-Options: nosniff');
    expect(text).toContain('Referrer-Policy: strict-origin-when-cross-origin');
  });

  it('allows no frame without a runner, and refuses a runner on the API origin', () => {
    expect(headersFile({})).toContain("frame-src 'none'");
    expect(
      headersFile({
        NEXT_PUBLIC_API_URL: 'https://api.example.com',
        NEXT_PUBLIC_SANDBOX_ORIGIN: 'https://api.example.com/runner',
      }),
    ).toContain("frame-src 'none'");
  });
});
